-- EXEMPLO USANDO O UNION
USE AdventureWorks2017;

SELECT CITY
FROM PERSON.ADDRESS
WHERE ADDRESSID < 15000

UNION

SELECT CITY
FROM PERSON.ADDRESS
WHERE ADDRESSID >= 15000
ORDER BY CITY


-- EXEMPLO USANDO O UNION ALL

SELECT CITY
FROM PERSON.ADDRESS
WHERE ADDRESSID < 15000

UNION ALL

SELECT CITY
FROM PERSON.ADDRESS
WHERE ADDRESSID >= 15000
ORDER BY CITY

-- EXEMPLO USANDO UNION
USE crm;

SELECT CIDADE,
	   CODIGO_PAIS
FROM CLIENTE
WHERE CODIGO_PAIS = 'US'

UNION

SELECT CIDADE,
	   CODIGO_PAIS
FROM CLIENTE
WHERE CODIGO_PAIS = 'BR'
ORDER BY CIDADE

