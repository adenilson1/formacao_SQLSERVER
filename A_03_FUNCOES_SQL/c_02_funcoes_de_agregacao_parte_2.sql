SELECT A.NOME_MONTADORA,
       B.NOME_CARRO,
	   COUNT(*) AS 'QTD',
	   GROUPING(A.NOME_MONTADORA) AS 'GROUPING'
FROM MONTADORA A 
INNER JOIN CARRO_MONTADORA B
ON A.ID_MONTADORA = B.ID_MONTADORA
WHERE A.NOME_MONTADORA IN ('TOYOTA', 'ALFA ROMEO')
GROUP BY A.NOME_MONTADORA,
	     B.NOME_CARRO 
WITH ROLLUP;

-- TRAZENDO O NOME CIDADE COM MAIOR PUPULACAO EM CADA ESTADO
USE CURSO;

SELECT A. * FROM
	  (SELECT COD_UF,
	          MAX(POPULACAO) AS POPULACAO
	    FROM SENSO
        GROUP BY COD_UF) B
JOIN SENSO A
ON A.COD_UF = B.COD_UF
AND A.POPULACAO = B.POPULACAO
ORDER BY A.POPULACAO DESC;

SELECT A. * FROM
	  (SELECT COD_UF,
	          MIN(POPULACAO) AS POPULACAO
	    FROM SENSO
        GROUP BY COD_UF) B
JOIN SENSO A
ON A.COD_UF = B.COD_UF
AND A.POPULACAO = B.POPULACAO
ORDER BY A.POPULACAO DESC;

-- OUTRO EXEMPLO
SELECT A.COD_UF,
	   A.NOME_MUN,
	   A.POPULACAO
FROM SENSO A
GROUP BY A.COD_UF,
         A.NOME_MUN,
		 A.POPULACAO
HAVING POPULACAO = (
	                 SELECT MAX(POPULACAO) 
					 FROM SENSO
					 WHERE COD_UF = A.COD_UF
					 )
ORDER BY A.POPULACAO DESC;

