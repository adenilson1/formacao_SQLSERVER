-- FUNÇÕES DE MATEMATICAS
-- UMA FUNÇÃO MATEMÁTICA QUE RETORNA O VALOR ABSOLUTO (POSITIVO)
-- DA EXPRESSÃO NUMÉRICA ESPECIFICADA

SELECT ABS(-1.0), ABS(0.0), ABS(1.0), ABS(-9.0), ABS(9.0), ABS(-5.4), ABS(5.4);

-- RAND 
-- RETORNA UM VALOR FLOAT PSEUDOALEATÓRIO DE 0 A 1, EXCLUISIVO

SELECT RAND(), RAND(), RAND();

-- EXEMPLO
DECLARE @CONT SMALLINT;
SET @CONT = 1;
WHILE @CONT < 5
	BEGIN 
		SELECT RAND() RANDOM_NUMBER
		SET @CONT = @CONT + 1
	END;

-- ROUND 
-- RETORNA UM VALOR NUÉRICO, ARRENDONDADO, PARA O COMPRIMENTO OU PRESISÃO ESPECIFICADOS

SELECT ROUND(123.9994, 3), ROUND(123.9995, 3);

-- EXEMPLO 2
SELECT ROUND(123.4545, 2);
SELECT ROUND(123.45, -2);
SELECT ROUND(193.45, -2);

-- EXEMPLO 3
SELECT ROUND(150.75,0);
SELECT ROUND(150.75, 0.1);

-- FUNÇÃO POWER POTENCIA
SELECT POWER(2,2);
SELECT POWER(2,3);

DECLARE @VALOR INT=2,
	    @POTENCIA INT=4;
SELECT POWER(@VALOR, @POTENCIA);

-- SQRT RAIZ QUADRADA
SELECT SQRT(9);